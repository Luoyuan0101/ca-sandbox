/**
 * 海拔配色
 *
 * 为什么单独放一个文件？
 * ────────────────
 * 同一套配色有三个地方要，而且必须**逐字节一致**，
 * 否则图例上的渐变色和画布上真正的颜色对不上，会讓人怀疑数据：
 *   1. React 版画布（components/FireCanvas.tsx）
 *   2. 单文件预览版画布（preview/index.html）
 *   3. 两个版本里显示"低 → 高"的那条图例渐变色条
 *
 * 所以把色标定义在一处，两边都从这里取。
 *
 * 配色思路
 * ────────────────
 * 用的是最符合直觉的「地形色带」（和地形图、地貌沙盘一个逻辑）：
 *   水面  → 深青（海、湖）
 *   滩涂  → 浅沙
 *   低地  → 草绿（真正的绿洲在低处）
 *   丘陵  → 黄绿 → 土黄
 *   山地  → 棕
 *   高山  → 灰褐
 *   雪线  → 近白
 * 这条带子不需要任何解释，谁看都知道"亮的、白的 = 高"。
 */
/** 色标：[位置 0~1, R, G, B] */
const STOPS = [
    [0.0, 10, 45, 72], // 水面：深青蓝（最暗）
    [0.08, 22, 94, 146], // 浅水：明确的海蓝，不再发灰
    [0.13, 92, 118, 56], // 滩涂：灰绿黄
    [0.2, 80, 150, 46], // 低地草绿（真正的绿洲）
    [0.34, 146, 176, 78], // 缓坡黄绿
    [0.48, 186, 170, 96], // 丘陵暖土黄
    [0.62, 208, 176, 132], // 山地：暖褐
    [0.76, 216, 194, 168], // 高山灰褐
    [0.88, 228, 222, 210], // 裸岩
    [1.0, 250, 250, 252], // 雪线（最亮）
];
/* ------------------------------------------------------------
 * ★ 为什么这条色带值得写这么长的注释
 *
 * 用户的要求是"所有地图配色都加饱和"。植被配色那边顺利用上了，
 * 但海拔这条带子连着改歪了四次，每次都记一下，免得后人重蹈：
 *
 *   v1 原始版 —— 有个**真 bug**，不是审美问题：
 *       滩涂(h=0.13) 的亮度 0.498，比低地(h=0.20) 的 0.341 还高。
 *       于是海拔视图里「越亮 = 越高」这条基本读图逻辑，
 *       在 h∈[0.13, 0.20] 区间是**反的** —— 海滩看着比内陆低地还高。
 *       这个 bug 一直藏着，因为没有任何测试检查过单调性。
 *
 *   v2 暴力搜索 —— 我把目标设成"最大化饱和度"，只给了下界。
 *       程序忠实地把饱和度拉到 0.986，然后产出一张霓虹灯地图：
 *       滩涂 #A9F002 荧光柠檬绿、低地 #8BFD09 荧光绿。
 *       数字全绿，图没法看。教训：
 *       **"加大饱和度"是有上界的需求，写成"最大化"必然跑到极端。**
 *
 *   v3 手填 RGB —— 加了饱和度，但手估感知亮度估不准
 *       （HSL 的 l 和人眼感知亮度不是一回事），又踩断单调性两次。
 *
 *   v4 感知亮度约束搜索 —— 单调性从构造上成立了，
 *       但低地仍取到 S=0.671，整片低地铺开就是荧光地毯。
 *
 *   v5 定稿（当前）—— 换思路：**锚定原版的观感，只做有界的加饱和**。
 *       每段保留自己的"地貌身份"（水是蓝、低地是绿、
 *       山地是棕、雪线是白），颜色更实更浓，同时把亮度顺序彻底理顺。
 *
 * 定稿验收（用 .vt/elev-check.mjs 量的）：
 *   平均饱和度 0.316 → 0.441   （+39%）
 *   最高单段   0.509 → 0.756   （<0.80，是"浓"不是"荧光"）
 *   亮度单调   ❌ → ✅          （修掉了 v1 那个真 bug）
 *   最亮颜色   0.973 → 0.984
 *
 * ⚠️ 还有一条**很容易漏掉**的细节：
 *    色标点本身递增，**不代表**插值出来的中间色也递增。
 *    v5 第一次调完，10 个色标点全部严格递增，但插值曲线仍有 10 处回落 ——
 *    原因是我让"丘陵(168.1)"和"山地(169.6)"只差 1.5 个亮度单位。
 *    两个几乎等亮的端点之间做 RGB 线性插值，会在中段打摆，
 *    而这个摆幅是**人眼能看出来的**：那一段会显得"忽明忽暗"。
 *    把山地提亮到 179.6（和丘陵拉开 11.5）之后，插值回落降到 0。
 *    所以色标之间必须留出足够间隔 —— 现在最小间隔是 5.5 亮度单位，
 *    由 .vt/elev-check.mjs 里的零容差插值检查守着，改坏了会直接报错退出。
 * ---------------------------------------------------------- */
/**
 * 把 0~1 的海拔映射成颜色
 *
 * 返回 `rgb(...)` 字符串而不是 hex：
 * 画布上几万个格子，字符串拼接的开销比想象中可观，
 * 而且 rgb 形式一眼能看出插值对不对。
 */
export function elevationColor(h) {
    const v = h <= 0 ? 0 : h >= 1 ? 1 : h;
    let lo = STOPS[0];
    let hi = STOPS[STOPS.length - 1];
    for (let i = 0; i < STOPS.length - 1; i++) {
        if (v >= STOPS[i][0] && v <= STOPS[i + 1][0]) {
            lo = STOPS[i];
            hi = STOPS[i + 1];
            break;
        }
    }
    const span = hi[0] - lo[0] || 1;
    const t = (v - lo[0]) / span;
    const r = Math.round(lo[1] + (hi[1] - lo[1]) * t);
    const g = Math.round(lo[2] + (hi[2] - lo[2]) * t);
    const b = Math.round(lo[3] + (hi[3] - lo[3]) * t);
    return `rgb(${r},${g},${b})`;
}
/**
 * 预先把色带烤成一张 256 级的查找表
 *
 * 为什么？
 * ────────────────
 * 一张 512×122 的地图有 62,464 个格子。
 * 如果每格都跑一次 elevationColor（找区间 + 三次插值 + 字符串拼接），
 * 每帧就是六万多次字符串分配 —— 在低配机器上会明显掉帧。
 *
 * 烤成 256 项的表之后，一格只剩一次数组取值，快得多，
 * 而且 256 级在人眼看来和连续渐变色没有区别。
 */
export const ELEVATION_LUT = (() => {
    const out = new Array(256);
    for (let i = 0; i < 256; i++)
        out[i] = elevationColor(i / 255);
    return out;
})();
/** 查表：`h` 是 0~1 的海拔 */
export function elevationColorFast(h) {
    const i = (h <= 0 ? 0 : h >= 1 ? 255 : (h * 255) | 0) | 0;
    return ELEVATION_LUT[i];
}
/**
 * 给 CSS 用的渐变色条（图例上那条"低 → 高"）
 *
 * 和上面用的是同一组色标，所以图例和画布永远一致。
 */
export const ELEVATION_GRADIENT_CSS = `linear-gradient(90deg, ${STOPS.map(([p, r, g, b]) => `rgb(${r},${g},${b}) ${(p * 100).toFixed(0)}%`).join(", ")})`;
/**
 * 生成一段**不依赖 import** 的色带源码
 *
 * 为什么需要这个东西？
 * ────────────────
 * `scripts/build-docs.mjs` 要把代码内联成单文件。
 * 如果画布代码里写 `import { elevationColorFast } from "./elevation"`，
 * 内联之后就断了。
 * 所以让构建脚本直接把这张 LUT 以字面量的形式写进产物里 ——
 * 反正它只有 256 个字符串，几 KB 而已。
 */
export function elevationLutLiteral() {
    return `[${ELEVATION_LUT.map((s) => JSON.stringify(s)).join(",")}]`;
}
