/**
 * 判断一个经纬度点是否在多边形内（射线法 / 奇偶规则）
 *
 * 这是最经典的点在多边形内判定：
 * 从该点向右射一条水平线，数它穿过多少条边。
 * 奇数次 = 在里面，偶数次 = 在外面。
 */
function pointInPolygon(lon: number, lat: number, poly: number[][]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    // 这条边是否跨过 lat 这条纬线？
    const intersects = yi > lat !== yj > lat;
    if (intersects) {
      // 求交点的经度，看是否在 lon 右侧
      const xCross = ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
      if (lon < xCross) inside = !inside;
    }
  }
  return inside;
}

/** 点是否落在某个区域的陆地上（不在任何湖里） */
export function isLand(region: Region, lon: number, lat: number): boolean {
  let onLand = false;
  for (const poly of region.land) {
    if (pointInPolygon(lon, lat, poly)) {
      onLand = true;
      break;
    }
  }
  if (!onLand) return false;
  // 湖 / 内海反过来算水
  for (const lake of region.lakes) {
    if (pointInPolygon(lon, lat, lake)) return false;
  }
  return true;
}

/**
 * 按纬度算气候带的基础湿度
 *
 * 这是真实存在的大气环流格局，不是随便编的：
 *   - 赤道附近（|lat| < 10）：上升气流，全年多雨 → 最湿
 *   - 副热带高压带（|lat| 15~35）：下沉气流，干旱 → 沙漠带
 *     （撒哈拉、阿拉伯、塔尔沙漠都在这一带）
 *   - 中纬度（|lat| 40~60）：西风带，气旋活动，降水增加 → 较湿
 *   - 极地（|lat| > 65）：冷，蒸发弱，有效湿度中等
 *
 * 同时它决定了该种什么：
 *   热带雨林 / 亚热带常绿 / 温带阔叶 / 寒温带针叶 / 苔原
 */
export function latitudeHumidity(lat: number): number {
  const a = Math.abs(lat);
  if (a < 10) return 0.82; // 赤道雨林
  if (a < 18) return 0.62;
  if (a < 30) return 0.28; // 副热带干旱带（沙漠）
  if (a < 40) return 0.42; // 地中海气候
  if (a < 55) return 0.6; // 温带西风带
  if (a < 65) return 0.55; // 寒温带
  return 0.45; // 苔原
}

/**
 * 按纬度算年平均气温的粗略估计（摄氏度）
 *
 * 用简单的余弦近似：赤道约 27°C，极地约 -15°C。
 * 不追求精确，只要能把「西伯利亚的冬天」和「印度的夏天」区分开。
 */
export function latitudeTemp(lat: number): number {
  const a = Math.abs(lat);
  return 27 - 42 * (a / 90) ** 1.3;
}
