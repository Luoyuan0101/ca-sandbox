/**
 * 真实世界地图数据（图集）
 *
 * 数据形式：经纬度多边形轮廓。
 * 为什么用多边形而不是位图？
 *   1. 多边形是**矢量**的 —— 放大到任何网格分辨率都不会糊
 *   2. 纯文本，能直接内联进单文件部署版，不依赖任何外部图片
 *   3. 数据量小（几 KB），加载快，GitHub Pages 上零延迟
 *
 * 坐标约定：[经度, 纬度]，都是十进制度。
 *   经度 -180 ~ 180（东经为正），纬度 -90 ~ 90（北纬为正）
 *
 * 精度说明：
 *   这些轮廓是**简化**过的（保留大尺度海岸线特征，忽略小岛和细碎海湾），
 *   目的是让「这是哪一块大陆」一眼可辨，而不是做导航用。
 *   在 3.2 km 分辨率的火场尺度上，这个精度完全够用 ——
 *   重点看的是「海陆分布 + 气候带植被」，不是海岸线的每一处曲折。
 */

export interface Region {
  id: string;
  name: string;
  /** 一句话说明这块地图是什么 */
  desc: string;
  /** 经纬度包围盒 [西, 南, 东, 北] */
  bbox: [number, number, number, number];
  /** 陆地区域（多边形列表，每个是 [lon, lat][]） */
  land: number[][][];
  /** 主要湖泊/内海（也当作水面，多边形） */
  lakes: number[][][];
}

